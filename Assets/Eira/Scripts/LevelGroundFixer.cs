using UnityEngine;

namespace EiraGame
{
    /// <summary>
    /// Repara el nivel en tiempo de ejecución: cuando el grupo "Gameplay" se
    /// recolocó sobre el claro del bosque, los objetos que quedaron fuera de la
    /// planicie se quedaron flotando en el aire y sin suelo debajo (solo la
    /// primera mitad del recorrido tenía piso). Esto:
    ///
    ///   1. calcula la extensión real del recorrido,
    ///   2. crea un suelo continuo bajo todo él (a la altura del piso del
    ///      bosque) para que Eira nunca caiga al vacío, y
    ///   3. baja cada objeto flotante hasta apoyarlo.
    ///
    /// Se ejecuta antes que los Start de drones y jugador, así que los puntos
    /// de patrulla y los checkpoints se fijan ya con las posiciones buenas.
    /// </summary>
    [DefaultExecutionOrder(-400)]
    public class LevelGroundFixer : MonoBehaviour
    {
        [Tooltip("Desactívalo para dejar la escena tal cual está.")]
        public bool repair = true;

        [Tooltip("Altura a la que se coloca el centro de los drones sobre el suelo.")]
        public float droneHover = 1.6f;

        [Tooltip("Margen de suelo generado alrededor del recorrido.")]
        public float margin = 14f;

        [Tooltip("Diferencia mínima (m) para considerar que un objeto está flotando.")]
        public float floatTolerance = 0.35f;

        void Awake()
        {
            if (!repair)
                return;

            // Avoid modifying objects generated by the professional reconstructor
            if (GameObject.Find("EIRA_Level1_Generated") != null)
            {
                Debug.Log("[LevelGroundFixer] Scenario generated by Reconstructor detected. Skipping auto-repair to avoid corruption.");
                return;
            }

            GameObject gameplay = GameObject.Find("Gameplay");

            if (gameplay == null)
                return;

            if (gameplay == null)
                return;

            Bounds bounds;

            if (!TryBounds(gameplay, out bounds) || bounds.size.sqrMagnitude < 0.01f)
                return;

            // El paisaje del bosque (árboles/pasto) vive fuera del grupo
            // Gameplay, así que el suelo continuo también debe cubrir su
            // extensión: al quitarle los colliders al modelo, si no hubiera
            // suelo bajo el bosque, Eira caería al vacío al pisar el pasto.
            EncapsulateLandscape(ref bounds);

            float groundY = ResolveGroundY(bounds);

            EnsureGround(bounds, groundY);

            int moved = SnapChildren(gameplay.transform, groundY);

            Debug.Log(
                "[LevelGroundFixer] suelo a y=" + groundY.ToString("0.00") +
                " extensión " + bounds.size.x.ToString("0") + "x" + bounds.size.z.ToString("0") +
                " objetos recolocados=" + moved);
        }

        // =========================================================
        // SUELO
        // =========================================================

        /// <summary>
        /// Expande la envolvente para incluir el paisaje del bosque (árboles y
        /// pasto), que no cuelga del grupo Gameplay. Así el suelo generado
        /// cubre toda la zona por la que Eira puede caminar.
        /// </summary>
        static void EncapsulateLandscape(ref Bounds bounds)
        {
            string[] names =
            {
                "PaisajeNivel1_Environment",
                "PaisajeNivel1",
                "Paisaje",
                "Bosque"
            };

            for (int i = 0; i < names.Length; i++)
            {
                GameObject go = GameObject.Find(names[i]);

                if (go == null)
                    continue;

                Bounds lb;

                if (TryBounds(go, out lb) && lb.size.sqrMagnitude > 0.01f)
                    bounds.Encapsulate(lb);
            }
        }

        /// <summary>
        /// Altura del suelo de referencia. Se toma del piso del bosque
        /// (PisoBosque) si existe; si no, del objeto más bajo del recorrido.
        /// </summary>
        float ResolveGroundY(Bounds bounds)
        {
            GameObject piso = GameObject.Find("PisoBosque");

            if (piso != null)
            {
                Renderer r = piso.GetComponentInChildren<Renderer>();

                if (r != null)
                    return r.bounds.max.y;
            }

            return bounds.min.y;
        }

        void EnsureGround(Bounds bounds, float groundY)
        {
            GameObject go = GameObject.CreatePrimitive(PrimitiveType.Plane);
            go.name = "AutoGround";
            go.isStatic = true;

            // Un pelín por debajo del piso existente para no pelearse (z-fight)
            // con la planicie del bosque donde ya hay suelo.
            go.transform.position = new Vector3(
                bounds.center.x,
                groundY - 0.06f,
                bounds.center.z);

            go.transform.localScale = new Vector3(
                (bounds.size.x + margin * 2f) / 10f,
                1f,
                (bounds.size.z + margin * 2f) / 10f);

            Renderer mr = go.GetComponent<Renderer>();

            if (mr != null)
            {
                GameObject piso = GameObject.Find("PisoBosque");

                if (piso != null && piso.GetComponentInChildren<Renderer>() != null)
                {
                    mr.sharedMaterial = piso.GetComponentInChildren<Renderer>().sharedMaterial;
                }
                else
                {
                    mr.sharedMaterial = CombatFX.LitMaterial(new Color(0.16f, 0.22f, 0.14f));
                }
            }
        }

        // =========================================================
        // SENTAR OBJETOS
        // =========================================================

        int SnapChildren(Transform gameplay, float groundY)
        {
            int moved = 0;

            for (int i = 0; i < gameplay.childCount; i++)
            {
                Transform child = gameplay.GetChild(i);

                if (child == null)
                    continue;

                Bounds cb;

                if (!TryBounds(child.gameObject, out cb))
                    continue;

                DroneController drone = child.GetComponentInChildren<DroneController>();

                float delta;

                if (drone != null)
                {
                    // Los drones van volando: se les da una altura de crucero
                    // sobre el suelo en vez de apoyarlos.
                    delta = (groundY + droneHover) - cb.center.y;
                }
                else
                {
                    delta = groundY - cb.min.y;
                }

                if (Mathf.Abs(delta) < floatTolerance)
                    continue;

                child.position += new Vector3(0f, delta, 0f);
                moved++;
            }

            return moved;
        }

        /// <summary>
        /// Envolvente de todos los colliders/renderers del objeto (sin
        /// sistemas de partículas, que tienen bounds enormes y falsos).
        /// Es pública y reutilizable: la ambientación del nivel la usa para
        /// alinear el neón con el recorrido real en vez de con coordenadas
        /// fijas de un nivel que ya no está donde se creó.
        /// </summary>
        public static bool TryBounds(GameObject go, out Bounds bounds)
        {
            bounds = new Bounds(go.transform.position, Vector3.zero);
            bool any = false;

            Collider[] cols = go.GetComponentsInChildren<Collider>(true);

            for (int i = 0; i < cols.Length; i++)
            {
                if (cols[i] == null)
                    continue;

                if (!any)
                {
                    bounds = cols[i].bounds;
                    any = true;
                }
                else
                {
                    bounds.Encapsulate(cols[i].bounds);
                }
            }

            if (any)
                return true;

            Renderer[] rs = go.GetComponentsInChildren<Renderer>(true);

            for (int i = 0; i < rs.Length; i++)
            {
                if (rs[i] == null || rs[i] is ParticleSystemRenderer)
                    continue;

                if (!any)
                {
                    bounds = rs[i].bounds;
                    any = true;
                }
                else
                {
                    bounds.Encapsulate(rs[i].bounds);
                }
            }

            return any;
        }
    }
}
